export function uiText(language, englishText, vietnameseText = englishText) {
  const id = normalizeLanguage(language);
  if (id === 'vi') return vietnameseText;
  if (id === 'en') return englishText;
  return PHRASES[id]?.[englishText] || englishText;
}

export function t(language, key) {
  const id = normalizeLanguage(language);
  return DICTIONARY_BY_ID[id]?.[key] || en[key] || key;
}
